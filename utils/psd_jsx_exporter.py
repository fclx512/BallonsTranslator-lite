class PsJsxExporter(AbstractPsdExporter):
    """Produce a single self-contained .jsx that rebuilds text layers in PS.

    No Photoshop dependency at export time — the script is plain text.
    """

    # ------------------------------------------------------------------
    # AbstractPsdExporter
    # ------------------------------------------------------------------

    def check_availability(self, passive: bool = False) -> Tuple[bool, str]:
        # Always available — JSX is plain-text output.
        return True, "ExtendScript can be run on any machine with Photoshop"

    def get_available_fonts(self) -> Set[str]:
        # We cannot enumerate PS fonts without COM.
        return set()

    def export_page(
        self,
        proj: ProjImgTrans,
        page_name: str,
        options: ExportOptions,
    ) -> str:
        """Export a single page as its own .jsx (interface compatibility)."""
        return self.export_batch(proj, [page_name], options)

    def export_batch(
        self,
        proj: ProjImgTrans,
        page_names: List[str],
        options: ExportOptions,
    ) -> str:
        """Generate ONE .jsx covering all *page_names*; returns its path.

        Run the resulting script once in Photoshop (File → Scripts → Browse)
        to recreate every page as an editable-text PSD.
        """
        os.makedirs(options.output_dir, exist_ok=True)

        pages = self._build_pages(proj, page_names, options)

        script = BATCH_SCRIPT_TEMPLATE.substitute(
            machine_name=os.environ.get("COMPUTERNAME", "unknown"),
            project_name=proj.proj_name(),
            page_count=len(page_names),
            pages_json=json.dumps(
                {"pages": pages}, ensure_ascii=False, separators=(",", ":")
            ),
            font_notes=self._build_font_notes(proj, page_names),
        )

        jsx_path = os.path.join(
            options.output_dir, proj.proj_name() + "_psd_export.jsx"
        )
        # UTF-8 with BOM — required for non-ASCII ExtendScript sources.
        with open(jsx_path, "w", encoding="utf-8-sig", newline="\n") as f:
            f.write(script)

        logger.info(
            "PSD export script written to %s (%d pages)", jsx_path, len(page_names)
        )
        return jsx_path

    def cleanup(self):
        pass  # nothing to release

    # ------------------------------------------------------------------
    # internal — payload construction
    # ------------------------------------------------------------------

    @staticmethod
    def _build_pages(
        proj: ProjImgTrans,
        page_names: List[str],
        options: ExportOptions,
    ) -> List[Dict]:
        """Build the per-page payload embedded in the .jsx."""
        pages: List[Dict] = []
        for page_name in page_names:
            src = os.path.join(proj.directory, page_name)
            dpi = PsJsxExporter._read_image_dpi(src)

            blocks = []
            for idx, blk in enumerate(proj.pages.get(page_name, []), 1):
                if not blk.translation or not blk.translation.strip():
                    continue
                blocks.append(
                    PsJsxExporter._block_payload(blk, idx, dpi, options.center_align)
                )

            pages.append(
                {
                    "name": page_name,
                    "path": PsJsxExporter._js_path(src),
                    "dpi": dpi,
                    "out_path": PsJsxExporter._js_path(
                        os.path.join(
                            options.output_dir,
                            os.path.splitext(page_name)[0] + ".psd",
                        )
                    ),
                    "blocks": blocks,
                }
            )
        return pages

    @staticmethod
    def _block_payload(blk, index: int, dpi: float, center: bool) -> Dict:
        """Convert one TextBlock → the JS layer descriptor dict."""
        ff = blk.fontformat
        x1, y1, x2, y2 = blk.xyxy
        font_size = float(ff.font_size) if ff.font_size else 1.0

        resolved, _ = resolve_font_name(ff.font_family, ps_available=None)

        # Point size so the rendered pixel height matches the source block:
        #   pt = px * 72 / image_dpi    (PS renders pt at the doc resolution)
        size_pt = round(font_size * 72.0 / dpi, 2)

        # Line spacing → PS auto-leading percentage.
        if ff.line_spacing_type == LineSpacingType.Distance and font_size > 0:
            line_spacing = round(float(ff.line_spacing) / font_size * 100.0, 2)
        else:
            line_spacing = round(float(ff.line_spacing) * 100.0, 2)

        # Stroke pen width (matches effect_renderer: font_size × stroke_width).
        stroke_width = float(ff.stroke_width) if ff.stroke_width else 0.0
        stroke_size = round(font_size * stroke_width, 2) if stroke_width > 0 else 0.0

        # Shadow blur / distance / opacity (matches effect_renderer formulas).
        shadow_radius = float(ff.shadow_radius) if ff.shadow_radius else 0.0
        shadow_strength = float(ff.shadow_strength) if ff.shadow_strength else 0.0
        ox, oy = (float(v) for v in ff.shadow_offset)
        if shadow_radius > 0 and shadow_strength > 0:
            shadow_blur = round(shadow_radius * font_size, 2)
            shadow_opacity = int(shadow_strength * 100)
            shadow_distance = round(math.hypot(ox, oy) * font_size, 2)
            # PS interprets the angle as the LIGHT source; shadow falls opposite
            # the offset, hence the 180° flip.
            shadow_angle = round(
                (math.degrees(math.atan2(-oy, ox)) + 180.0) % 360.0, 2
            )
        else:
            shadow_blur = 0.0
            shadow_opacity = 0
            shadow_distance = 0.0
            shadow_angle = 0.0

        return {
            "name": (
                f"TL {index:03d} "
                f"{blk.translation[:20].replace(chr(10), ' ').replace(chr(13), ' ')}"
            ),
            "text": blk.translation.strip(),
            "font": resolved,
            "size_pt": size_pt,
            "size_px": round(font_size, 2),
            "color": ff.foreground_color(),
            "bold": bool(ff.bold),
            "italic": bool(ff.italic),
            "underline": bool(ff.underline),
            "vertical": bool(ff.vertical),
            "alignment": int(ff.alignment),
            "opacity": float(ff.opacity) if ff.opacity is not None else 1.0,
            "line_spacing": line_spacing,
            "box": [round(float(v), 1) for v in (x1, y1, x2, y2)],
            "stroke_size": stroke_size,
            "stroke_color": ff.stroke_color() if stroke_width > 0 else [0, 0, 0],
            "shadow_blur": shadow_blur,
            "shadow_opacity": shadow_opacity,
            "shadow_distance": shadow_distance,
            "shadow_angle": shadow_angle,
            "shadow_color": list(ff.shadow_color),
            "rotation": round(float(blk.angle), 2),
            "center": bool(center),
        }

    @staticmethod
    def _build_font_notes(proj: ProjImgTrans, page_names: List[str]) -> str:
        """Generate JS comments noting which fonts may need manual adjustment."""
        families: List[str] = []
        for page_name in page_names:
            for blk in proj.pages.get(page_name, []):
                fam = blk.fontformat.font_family
                if fam and fam not in families:
                    families.append(fam)

        lines = ["// Font compatibility notes:"]
        for fam in sorted(families):
            mapped, _ = resolve_font_name(fam, ps_available=None)
            if mapped != fam:
                lines.append(f"//   '{fam}' → '{mapped}' (auto-mapped)")
            else:
                lines.append(
                    f"//   '{fam}' — verify this font is installed in Photoshop"
                )
        lines.append("//")
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # internal — helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _read_image_dpi(img_path: str) -> float:
        """Read the DPI of a source image using PIL; 96.0 as fallback."""
        try:
            from PIL import Image as PILImage

            with PILImage.open(img_path) as img:
                dpi_info = img.info.get("dpi")
                if dpi_info and len(dpi_info) >= 2:
                    dpi = max(dpi_info[0], dpi_info[1], 72.0)
                    logger.debug("Image DPI: %.1f (from %s)", dpi, img_path)
                    return dpi
        except Exception:
            pass
        logger.debug("Could not read DPI from '%s', falling back to 96.0", img_path)
        return 96.0

    @staticmethod
    def _js_path(path: str) -> str:
        """ExtendScript accepts forward slashes on Windows too."""
        return path.replace("\\", "/")
