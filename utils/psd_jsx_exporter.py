"""ExtendScript (.jsx) batch PSD exporter.

Generates a single self-contained Adobe ExtendScript that, when run inside
Photoshop (File → Scripts → Browse), recreates the project's text blocks as
editable text layers across all selected pages and saves each page as PSD.

Mechanism (mirrors the LabelPlus PS-Script fork ZsIsMe/PS-Script):
- ``artLayers.add()`` + ``kind = LayerKind.TEXT`` + ``textItem.*`` DOM calls
- rotation via ``artLayer.rotate(-deg)`` — source data (BallonsTranslator) is
  CCW+, Photoshop is CW+, so the sign is flipped
- stroke / drop shadow via layer-style ActionDescriptor (``frameFX`` /
  ``dropShadow``)
- center-align fallback: translate the layer so its bounds center equals the
  block box center, compensating for PS-vs-local font-metric differences

The page data (Meo-style JSON) is embedded directly into the .jsx so there is
no external file / BOM / encoding dance at run time.  The output file itself
is written UTF-8 with BOM, matching the LabelPlus PS-Script distribution
convention for non-ASCII ExtendScript sources.
"""

import json
import logging
import math
import os
from string import Template
from typing import Dict, List, Optional, Set, Tuple

from .font_mapping import resolve_font_name
from .fontformat import LineSpacingType
from .proj_imgtrans import ProjImgTrans
from .psd_exporter import AbstractPsdExporter, ExportOptions

logger = logging.getLogger(__name__)

# ==============================================================================
# ExtendScript template
# ==============================================================================
# The template uses Python string.Template placeholders:
#   $machine_name — host name (header comment)
#   $project_name — project name (header comment)
#   $page_count   — number of pages (header comment)
#   $pages_json   — JSON payload object (embedded JS literal)
#   $font_notes   — JS comments about font compatibility
#
# IMPORTANT: the JS code must not contain a literal "$", otherwise
# string.Template treats it as a placeholder.
# ==============================================================================

BATCH_SCRIPT_TEMPLATE = Template(
    r"""#target photoshop
// =============================================================================
// Auto-generated by BallonsTranslator — batch PSD exporter (ExtendScript)
//
// Recreates the project's text blocks as editable text layers, one PSD per
// page.  Run once in Photoshop:  File → Scripts → Browse → select this file.
//
// Machine:  $machine_name
// Project:  $project_name
// Pages:    $page_count
// =============================================================================

app.bringToFront();

// --- helpers ----------------------------------------------------------------

function makeSolidColor(r, g, b) {
    var c = new SolidColor();
    c.rgb.red   = r;
    c.rgb.green = g;
    c.rgb.blue  = b;
    return c;
}

// Stroke (frameFX) + drop shadow via layer-style ActionDescriptor.
function applyLayerEffects(layer, blk) {
    try {
        var hasStroke = blk.stroke_size > 0;
        var hasShadow = blk.shadow_opacity > 0 && blk.shadow_blur > 0;
        if (!hasStroke && !hasShadow) return;

        var desc = new ActionDescriptor();
        var ref = new ActionReference();
        ref.putEnumerated(charIDToTypeID("Lyr "), charIDToTypeID("Ordn"), charIDToTypeID("Trgt"));
        desc.putReference(charIDToTypeID("null"), ref);

        var layerEffects = new ActionDescriptor();

        if (hasStroke) {
            var strokeDesc = new ActionDescriptor();
            strokeDesc.putBoolean(stringIDToTypeID("enabled"), true);
            strokeDesc.putEnumerated(stringIDToTypeID("style"), stringIDToTypeID("frameStyle"), stringIDToTypeID("outsetFrame"));
            strokeDesc.putUnitDouble(stringIDToTypeID("size"), charIDToTypeID("#Pxl"), blk.stroke_size);
            var sc = new ActionDescriptor();
            sc.putDouble(charIDToTypeID("Rd  "), blk.stroke_color[0]);
            sc.putDouble(charIDToTypeID("Grn "), blk.stroke_color[1]);
            sc.putDouble(charIDToTypeID("Bl  "), blk.stroke_color[2]);
            strokeDesc.putObject(stringIDToTypeID("color"), charIDToTypeID("RGBC"), sc);
            layerEffects.putObject(stringIDToTypeID("frameFX"), stringIDToTypeID("frameFX"), strokeDesc);
        }

        if (hasShadow) {
            var shadowDesc = new ActionDescriptor();
            shadowDesc.putBoolean(stringIDToTypeID("enabled"), true);
            shadowDesc.putEnumerated(stringIDToTypeID("mode"), charIDToTypeID("BlnM"), charIDToTypeID("Mltp"));
            shadowDesc.putUnitDouble(stringIDToTypeID("opacity"), charIDToTypeID("#Prc"), blk.shadow_opacity);
            shadowDesc.putBoolean(stringIDToTypeID("useGlobalAngle"), false);
            shadowDesc.putUnitDouble(stringIDToTypeID("localLightingAngle"), charIDToTypeID("#Ang"), blk.shadow_angle);
            shadowDesc.putUnitDouble(stringIDToTypeID("angle"), charIDToTypeID("#Ang"), blk.shadow_angle);
            shadowDesc.putUnitDouble(stringIDToTypeID("blur"), charIDToTypeID("#Pxl"), blk.shadow_blur);
            shadowDesc.putUnitDouble(stringIDToTypeID("distance"), charIDToTypeID("#Pxl"), blk.shadow_distance);
            var sc2 = new ActionDescriptor();
            sc2.putDouble(charIDToTypeID("Rd  "), blk.shadow_color[0]);
            sc2.putDouble(charIDToTypeID("Grn "), blk.shadow_color[1]);
            sc2.putDouble(charIDToTypeID("Bl  "), blk.shadow_color[2]);
            shadowDesc.putObject(stringIDToTypeID("color"), charIDToTypeID("RGBC"), sc2);
            layerEffects.putObject(stringIDToTypeID("dropShadow"), stringIDToTypeID("dropShadow"), shadowDesc);
        }

        desc.putObject(charIDToTypeID("T   "), stringIDToTypeID("layerEffects"), layerEffects);
        executeAction(charIDToTypeID("setd"), desc, DialogModes.NO);
    } catch (e) {}
}

// Create one editable text layer mirroring a project text block.
function createTextLayer(doc, blk) {
    var art = doc.artLayers.add();
    art.name = blk.name;
    art.kind = LayerKind.TEXT;
    var ti = art.textItem;

    try { ti.kind = TextType.POINT_TEXT; } catch (e) {}

    // Direction must be set BEFORE contents for reliable vertical text.
    if (blk.vertical) { try { ti.direction = Direction.VERTICAL; } catch (e) {} }

    ti.contents = blk.text;

    if (blk.font) { try { ti.font = blk.font; } catch (e) {} }
    if (blk.size_pt > 0) { try { ti.size = blk.size_pt; } catch (e) {} }
    try { ti.color = makeSolidColor(blk.color[0], blk.color[1], blk.color[2]); } catch (e) {}

    if (blk.bold)   { try { ti.fauxBold = true; } catch (e) {} }
    if (blk.italic) { try { ti.fauxItalic = true; } catch (e) {} }
    if (blk.underline) { try { ti.underline = true; } catch (e) {} }

    var alignMap = {0: Justification.LEFT, 1: Justification.CENTER, 2: Justification.RIGHT};
    try { ti.justification = alignMap[blk.alignment] || Justification.LEFT; } catch (e) {}

    // Line spacing → auto-leading percentage.
    if (blk.line_spacing > 0) {
        try { ti.useAutoLeading = true; ti.autoLeadingAmount = blk.line_spacing; } catch (e) {}
    }

    // Initial position near the block box (center-align corrects below).
    // Explicit px units — bare numbers would follow the current ruler unit.
    if (blk.vertical) {
        try { ti.position = [UnitValue(blk.box[2], 'px'), UnitValue(blk.box[1], 'px')]; } catch (e) {}
    } else {
        try { ti.position = [UnitValue(blk.box[0], 'px'), UnitValue(blk.box[1] + blk.size_px * 0.8, 'px')]; } catch (e) {}
    }

    if (blk.opacity < 1.0) { try { art.opacity = blk.opacity * 100; } catch (e) {} }

    // Rotation — BallonsTranslator is CCW+, Photoshop is CW+, so negate.
    if (blk.rotation) {
        try { art.rotate(-blk.rotation, AnchorPosition.MIDDLECENTER); } catch (e) {}
    }

    applyLayerEffects(art, blk);

    // Center-align fallback: shift the layer so its bounds center matches the
    // block box center, absorbing PS-vs-local font-metric differences.
    if (blk.center) {
        var ru = app.preferences.rulerUnits;
        app.preferences.rulerUnits = Units.PIXELS;
        try {
            var b = art.bounds;
            var w = b[2].as('px') - b[0].as('px');
            var h = b[3].as('px') - b[1].as('px');
            var cx = (blk.box[0] + blk.box[2]) / 2;
            var cy = (blk.box[1] + blk.box[3]) / 2;
            var curx = b[0].as('px') + w / 2;
            var cury = b[1].as('px') + h / 2;
            art.translate(UnitValue(cx - curx, 'px'), UnitValue(cy - cury, 'px'));
        } catch (e) {}
        finally { app.preferences.rulerUnits = ru; }
    }

    return art;
}

// Open one source image, add its text layers, save PSD.
function processPage(page) {
    var src = File(page.path);
    if (!src.exists) {
        alert("Missing source image:\n" + page.path);
        return false;
    }
    var doc = app.open(src);
    app.activeDocument = doc;

    // Normalize resolution so pt→px sizing matches the export-time computation.
    try { doc.resizeImage(undefined, undefined, page.dpi); } catch (e) {}

    for (var i = 0; i < page.blocks.length; i++) {
        try { createTextLayer(doc, page.blocks[i]); } catch (e) {}
    }

    var psdFile = File(page.out_path);
    var opts = new PhotoshopSaveOptions();
    opts.embedColorProfile = true;
    doc.saveAs(psdFile, opts, true);
    doc.close(SaveOptions.DONOTSAVECHANGES);
    return true;
}

// --- main -------------------------------------------------------------------

$font_notes

var DATA = $pages_json;

var done = 0;
var skipped = 0;
for (var p = 0; p < DATA.pages.length; p++) {
    if (processPage(DATA.pages[p])) { done++; }
    else { skipped++; }
}

var summary = "Exported " + done + " / " + DATA.pages.length + " PSD file(s).";
if (skipped > 0) { summary += "\n" + skipped + " page(s) skipped (missing image)."; }
alert(summary);
"""
)

